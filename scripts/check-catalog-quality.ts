import {readFile,writeFile} from "node:fs/promises";
import {coffeeProducts} from "../src/data/coffee-products.ts";
import type {Product} from "../src/types/product.ts";
import {catalogQualitySummary,qualityActions} from "./lib/catalog-quality-summary.ts";
const args=process.argv.slice(2);
if(args.some(arg=>!["--check","--details"].includes(arg)))throw Error("--check와 --details만 지원합니다.");
const data=new URL("../src/data/",import.meta.url);
const read=async(name:string)=>JSON.parse(await readFile(new URL(name,data),"utf8"));
const decisions=await read("review-decisions.json"),automatic=await read("auto-review.json");
const products=[...await read("products.json"),...coffeeProducts].map((p:Product)=>({...p,reviewStatus:decisions[p.id]?.decision??automatic.products[p.id]?.decision??p.reviewStatus}));
const health=await read("collection-health.json").catch(error=>{if(error.code==="ENOENT")return undefined;throw error;});
const now=new Date();
const report={checkedAt:now.toISOString(),scope:"로컬 저장 데이터와 현재 공개 필터만 검사. 오래된 운영 기록은 실제 장애의 증거가 아님. 외부 NEW·이미지 응답·실기기 상태는 검증하지 않음",...catalogQualitySummary(products,health,now)};
if(!args.includes("--check"))await writeFile(new URL("../docs/catalog-quality-current.json",import.meta.url),JSON.stringify(report,null,2)+"\n");
console.log(JSON.stringify({total:report.total,published:report.published,errors:report.errors.length,gaps:report.gaps.length,issueCounts:report.summary.issueCounts,snapshot:report.summary.snapshot,attentionBrands:report.summary.brands.length}));
if(args.includes("--details"))for(const brand of report.summary.brands)console.log(JSON.stringify({...brand,actions:brand.actions.map(code=>({code,description:qualityActions[code]}))}));
if(report.errors.length)process.exitCode=1;
